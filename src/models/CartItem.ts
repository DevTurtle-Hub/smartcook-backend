import mongoose, { Document, Model, Schema } from "mongoose";
import { normalizeVietnamese } from "../utils/text";

export interface ICartItem extends Document {
  userId: mongoose.Types.ObjectId;
  name: string;
  normalizedName: string;
  amount: string;
  price: number;
  category: string;
  recipeTitle?: string;
  recipeId?: mongoose.Types.ObjectId;
  bought: boolean;
  isAutoGenerated: boolean;
  syncedToFridge: boolean;
  addedAt: Date;
  createdAt: Date;
  updatedAt: Date;
}

const CartItemSchema = new Schema<ICartItem>(
  {
    userId: {
      type: Schema.Types.ObjectId,
      ref: "User",
      required: true,
      index: true,
    },
    name: {
      type: String,
      required: [true, "Item name is required"],
      trim: true,
    },
    normalizedName: {
      type: String,
      required: true,
      trim: true,
    },
    amount: {
      type: String,
      default: "1",
      trim: true,
    },
    price: {
      type: Number,
      default: 0,
      min: 0,
    },
    category: {
      type: String,
      default: "Rau củ",
      trim: true,
    },
    recipeTitle: {
      type: String,
      trim: true,
    },
    recipeId: {
      type: Schema.Types.ObjectId,
      ref: "Recipe",
    },
    bought: {
      type: Boolean,
      default: false,
      index: true,
    },
    isAutoGenerated: {
      type: Boolean,
      default: false,
    },
    syncedToFridge: {
      type: Boolean,
      default: false,
    },
    addedAt: {
      type: Date,
      default: Date.now,
    },
  },
  {
    timestamps: true,
    toJSON: {
      virtuals: true,
      transform: (_, ret: any) => {
        delete ret.__v;
        return ret;
      },
    },
    toObject: { virtuals: true },
  }
);

CartItemSchema.pre<ICartItem>("validate", function () {
  if (this.name) {
    this.normalizedName = normalizeVietnamese(this.name);
  }
});

CartItemSchema.index({ userId: 1, bought: 1 });
CartItemSchema.index({ userId: 1, normalizedName: 1 });

export const CartItem: Model<ICartItem> = mongoose.model<ICartItem>(
  "CartItem",
  CartItemSchema
);
